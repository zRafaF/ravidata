def md(df, floatfmt="{:.3f}"):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        cells = []
        for c in cols:
            v = r[c]
            if isinstance(v, (float, np.floating)):
                cells.append("" if not np.isfinite(v) else floatfmt.format(v))
            else:
                cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)


def _top(S):
    return S[S["take"].isna() & S.env.isna()].copy()


def _arc_outcome(at, det, tol=0.25):
    """found (share of frames with a truth) and early (share of all frames), as in score.summary's arc view."""
    ok, fd = np.isfinite(at), np.isfinite(det)
    found = float((ok & fd & (np.abs(det - at) <= tol)).sum() / max(1, ok.sum()))
    early = float((fd & (~ok | (det < at - tol))).sum() / max(1, len(at)))
    return found, early


def _const_at(at, max_early, tol=0.25):
    """Best fixed answer (m) and its found rate among those with early <= max_early (nan, 0 if none)."""
    best = (np.nan, 0.0)
    for c in np.arange(0.3, 6.0, 0.02):
        f, e = _arc_outcome(at, np.full(len(at), c), tol)
        if e <= max_early + 1e-9 and f > best[1]:
            best = (float(c), f)
    return best


def run():
    import pandas as pd
    C.set_quick(False)
    L = ["# RAVIDATA radar analysis: result tables", "",
         "Generated by `make report` from `results/analysis-v4/tables` (do not edit by hand). "
         "Definitions: `docs/analysis.md`. Interpretation: `FINDINGS.md`.", ""]
    runs = [json.loads(l) for l in (C.out_dir() / "runs.jsonl").read_text().splitlines() if l.strip()]
    runs = [r for r in runs if not r.get("quick")]
    if runs:
        R = pd.DataFrame(runs).groupby("step").agg(last=("time", "last"), minutes=("seconds", lambda x: x.iloc[-1] / 60),
                                                    commit=("commit", "last")).reset_index()
        L += ["## Runs (last of each step)", "", md(R, "{:.1f}"), ""]
    F = C.load_table("truth_frames", required=False)
    if F is not None:
        T = F.groupby("take").agg(radar_frames=("f", "size"), truth_source=("source", "first"),
                                  covered=("covered", "mean"), objects_per_frame=("n_obj", "mean"),
                                  arc_truth_median_m=("arc_r", "median"),
                                  arc_beam_covered=("arc_complete", lambda x: x.fillna(False).astype(bool).mean()),
                                  floor_below_camera_m=("floor_h", "median")).reset_index()
        L += ["## Ground truth per take", "", md(T, "{:.2f}"), ""]
    M = C.load_table("map_scale", required=False)
    if M is not None and len(M):
        Ms = M.groupby("take").ratio.describe(percentiles=[0.5]).reset_index()[["take", "count", "50%", "std"]]
        Ms.columns = ["take", "tag sightings", "tag / map depth (median)", "std"]
        L += ["## Map metric scale from the AprilTags (Pi3X)", "", md(Ms), ""]
    e = C.load_json("extrinsic", None)
    a = C.load_json("angle_calib", None)
    CM = C.load_table("calib_moving", required=False)          # the walking person: what the calibration is fitted on
    CT = C.load_table("calib_targets", required=False)         # still tags (several share a range bin: a weaker check)
    med = lambda T, c: float(np.median(np.abs(T[c]))) if T is not None and c in T else np.nan
    span = lambda T, c: f"{T[c].min():.0f}..{T[c].max():.0f}°" if T is not None and c in T else "?"
    if e and a:
        src = "the walking person" if CM is not None and "moving" in str(e.get("method", "")) else "still targets"
        R0 = CM if src == "the walking person" else CT
        L += ["## Calibration", "",
              f"- range bias {e['range_bias_m']:+.3f} m over {e['n_targets']} sightings of {src} "
              f"(residual rms {e['range_resid_rms_m']:.3f} m, MAD {e.get('range_resid_mad_m', np.nan):.3f} m); "
              f"radar placed at the camera (t_rc = 0)",
              f"- azimuth pair: sign {a['az']['sign']:+.0f}, offset {a['az']['offset_rad']:+.2f} rad, "
              f"consistency R {a['az']['R']:.2f}, median |residual| {med(R0, 'az_resid_deg'):.1f}° on {src} "
              f"({med(CT, 'az_resid_deg'):.1f}° on the still tags)",
              f"- elevation pair: sign {a['el']['sign']:+.0f}, offset {a['el']['offset_rad']:+.2f} rad, "
              f"consistency R {a['el']['R']:.2f}, median |residual| {med(R0, 'el_resid_deg'):.1f}° on {src} "
              f"(targets span {span(R0, 'el_true')}: approximate)", ""]
    Tm = C.load_table("timing", required=False)
    if Tm is not None:
        Tt = Tm.groupby("config").agg(recordings=("rec", "size"), fps=("fps", "median"), lost_pct=("lost_pct", "median"),
                                      jitter_std_ms=("dt_std_ms", "median"), dt_p99_ms=("dt_p99_ms", "median")).reset_index()
        L += ["## Frame timing per radar configuration", "", md(Tt, "{:.2f}"), ""]
    N = C.load_table("noise", required=False)
    if N is not None:
        S_ = N[N["take"].isin(C.STATIC)]
        use = (S_.r > 0.3) & (S_.r < 4.1)
        Nt = S_[use].groupby("config").agg(static_return_db=("mean_db", "median"), temporal_noise_db=("tvar_db", "median"),
                                           moving_doppler_db=("dop_db", "median")).reset_index()
        L += ["## Noise (static takes, 0.3-4.1 m, median over bins / RX; dB of full scale)", "", md(Nt, "{:.1f}"), ""]
    cols = ["family", "arc_pd", "arc_pd_lo", "arc_pd_hi", "arc_early_rate", "arc_err_m", "near_pd", "near_early_rate",
            "f1_50", "r_f1_50", "gospa"]
    for v, title in (("", "default settings"), ("_hgate", "default + IMU height gate"),
                     ("_tuned_pooled_arc", "tuned for the arc view (pooled)"),
                     ("_tuned_pooled_plane", "tuned per direction (pooled)")):
        S = C.load_table("eval_summary" + v, required=False)
        if S is None:
            continue
        A = _top(S)
        L += [f"## Detection, all takes, {title}", "",
              "arc_* = carried takes, nearest obstacle in the beam, direction ignored (found within 0.25 m / early "
              "alarm); near_* = nearest in the camera view; f1_50 = per 4° sector at 0.5 m; r_f1_50 = range only; "
              "lo/hi = 95 % block-bootstrap.", "", md(A[[c for c in cols if c in A]]), ""]
    for v, title in (("", "default"), ("_hgate", "default + IMU height gate"), ("_tuned_pooled_arc", "tuned arc")):
        S = C.load_table("eval_summary" + v, required=False)
        if S is None or "obj_pd" not in S:
            continue
        A = _top(S)[["family", "obj_pd", "obj_other_per_frame"]]
        L += [f"## Static takes, placed objects ({title}): found within 0.25 m (any angle), other returns per frame",
              "", md(A), ""]
    O = C.load_table("truth_objects", required=False)
    if O is not None and len(O):
        L += ["## Placed objects of the static takes (still chairs and brooms, radar frame)", "",
              md(O[["rec", "id", "kind", "r", "az", "el"]], "{:.2f}"), ""]
    for ob, key, sel in (("arc", "arc_pd", "tuned_arc"), ("plane", "f1_50", "tuned_f1")):
        R = C.load_table(f"opt_results_pooled_{ob}", required=False)
        if R is None:
            continue
        P = R[R.split.isin(["loto", "oracle"])].pivot_table(index="family", columns=["split", "selection"], values=key)
        P.columns = [f"{a}:{b}" for a, b in P.columns]
        L += [f"## Optimisation ({ob}): {key} on held-out takes (loto) vs the per-scene optimum (oracle)", "",
              md(P.reset_index()), ""]
    T = C.load_table("opt_trials_pooled_arc", required=False)
    if T is not None:
        rows = []
        for fam, g in T.groupby("family"):
            r = {"family": fam}
            for b in (0.05, 0.1, 0.2, 0.3):
                q = g[g.arc_early_rate <= b]
                r[f"found @ early<={int(b * 100)}%"] = q.arc_pd.max() if len(q) else np.nan
            d = g[g.trial == 0]
            r["default found"] = float(d.arc_pd.iloc[0]) if len(d) else np.nan
            r["default early"] = float(d.arc_early_rate.iloc[0]) if len(d) else np.nan
            rows.append(r)
        Fc = C.load_table("eval_frames", required=False)
        if Fc is not None and "arc_covered" in Fc:
            g = Fc[Fc.arc_covered.astype(bool) & (Fc.family == "thr")]
            r = {"family": "constant answer (no radar)"}
            for b in (0.05, 0.1, 0.2, 0.3):
                r[f"found @ early<={int(b * 100)}%"] = _const_at(g.arc_truth.to_numpy(), b)[1]
            rows.append(r)
        L += ["## Arc view at equal early-alarm budgets (best tuning trial per family)", "",
              "The last row is the chance floor: the best fixed distance answered in every frame, at the same budget.",
              "", md(pd.DataFrame(rows)), ""]
    rows = []
    for v, title in (("", "default"), ("_tuned_pooled_arc", "tuned arc (pooled: tuned on these takes)")):
        Fs = C.load_table("eval_frames" + v, required=False)
        if Fs is None or "arc_covered" not in Fs:
            continue
        Fs = Fs[Fs.arc_covered.astype(bool)]
        for (take, fam), g in Fs[Fs["take"].isin(C.CARRIED)].groupby(["take", "family"]):
            at, det = g.arc_truth.to_numpy(), g.arc_det.to_numpy()
            f, e = _arc_outcome(at, det)
            c, fc = _const_at(at, e)
            rows.append({"take": take, "settings": title, "family": fam, "found": f, "early": e,
                         "constant found, same early": fc, "constant (m)": c, "skill": f - fc})
    TFr = C.load_table("truth_frames", required=False)
    if TFr is not None and "arc_obs_r" in TFr:
        TFr = TFr.set_index(["rec", "f"])
        rows2 = []
        for v, title in (("", "default"), ("_tuned_pooled_arc", "tuned arc (pooled)")):
            Fs = C.load_table("eval_frames" + v, required=False)
            if Fs is None or "arc_covered" not in Fs:
                continue
            Fs = Fs[Fs.arc_covered.astype(bool) & Fs["take"].isin(C.CARRIED)]
            J = TFr.reindex(list(zip(Fs.rec, Fs.f)))
            gr = J.arc_floor_r.to_numpy() <= J.arc_obs_r.to_numpy()
            for (take, fam), idx in Fs.groupby(["take", "family"]).indices.items():
                at, det = Fs.arc_truth.to_numpy()[idx], Fs.arc_det.to_numpy()[idx]
                for case, m in (("ground nearest", gr[idx]), ("obstacle nearer than the ground", ~gr[idx])):
                    if m.sum() < 20:
                        continue
                    f, e = _arc_outcome(at[m], det[m])
                    err = np.abs(det[m] - at[m]); err = err[np.isfinite(err)]
                    rows2.append({"take": take, "settings": title, "family": fam, "case": case, "frames": int(m.sum()),
                                  "found": f, "early": e, "median |error| (m)": float(np.median(err)) if len(err) else np.nan})
        if rows2:
            L += ["## Ground nearest vs an obstacle nearer than the ground (carried takes, arc view)", "",
                  "The truth is the nearest thing in the beam, the ground included. When the ground is nearest the radar "
                  "works as an altimeter (the range is about its height); the events that matter are the frames with an "
                  "obstacle nearer than the ground.", "", md(pd.DataFrame(rows2), "{:.2f}"), ""]
    if rows:
        L += ["## Skill over the constant answer at the same early-alarm rate (carried takes, arc view)", "",
              "skill = found minus what the best fixed distance finds with no more early alarms than the detector.", "",
              md(pd.DataFrame(rows), "{:.2f}"), ""]
    Fr = C.load_table("eval_frames_tuned_pooled_arc", required=False)
    if Fr is not None and "arc_covered" in Fr:
        bins = [0.3, 0.5, 0.75, 1.0, 1.5, 2.0, 3.0, 8.0]
        rows = []
        for fam in ("ca_cfar", "grid", "grid_legacy", "rd_cfar", "thr"):
            x = Fr[(Fr.family == fam) & Fr.arc_covered.astype(bool)]
            at, ad = x.arc_truth.to_numpy(), x.arc_det.to_numpy()
            idx = np.digitize(at, bins)
            for i in range(1, len(bins)):
                m = np.isfinite(at) & (idx == i)
                n = int(m.sum())
                if not n:
                    continue
                rows.append(dict(family=fam, truth_m=f"{bins[i - 1]}-{bins[i]}", frames=n,
                                 found=float((np.isfinite(ad) & (np.abs(ad - at) <= 0.25))[m].mean()),
                                 early=float((np.isfinite(ad) & (ad < at - 0.25))[m].mean())))
        L += ["## Arc view by true obstacle distance (tuned for the arc view)", "", md(pd.DataFrame(rows), "{:.2f}"), ""]
    D = C.load_table("eval_dets_tuned_pooled_arc", required=False)
    if D is not None and len(D):
        Cz = D.groupby("family").cause.value_counts(normalize=True).unstack().fillna(0)
        Cz = Cz.rename(columns={"": "matched"}).reset_index()
        L += ["## What the unmatched detections are (share of all scored detections, tuned arc)", "", md(Cz, "{:.2f}"), ""]
    Fm = C.load_table("floor_margin", required=False)
    if Fm is not None:
        order = ["(-10.0, -1.0]", "(-1.0, -0.5]", "(-0.5, -0.25]", "(-0.25, 0.25]", "(0.25, 0.5]", "(0.5, 1.0]",
                 "(1.0, 10.0]"]
        for lab in ("tuned arc", "default"):
            x = Fm[(Fm.family == "ca_cfar") & (Fm.variant == lab)]
            if not len(x):
                continue
            W = x.pivot_table(index="margin", columns="env", values=["frames", "found", "early"]).reindex(order)
            W.columns = [f"{e} {v}" for v, e in W.columns]
            W = W[sorted(W.columns)].reset_index().rename(columns={"margin": "floor margin (m)"})
            for c in [c for c in W.columns if c.endswith("frames")]:
                W[c] = W[c].astype("Int64")
            L += [f"## Floor in the beam before the obstacle? (carried, CA-CFAR {lab}, obstacle beyond 0.75 m)", "",
                  "floor margin = range at which the floor enters the beam (+-30 deg elevation) minus the true nearest "
                  "obstacle range; negative = the floor comes first.", "", md(W, "{:.2f}"), ""]
    Fp = C.load_table("floor_pitch", required=False)
    if Fp is not None:
        pb = ["(-90, -25]", "(-25, -15]", "(-15, -5]", "(-5, 90]"]
        for env in sorted(set(Fp.env)):
            x = Fp[Fp.env == env]
            W = x.pivot_table(index="dist", columns="pitch_bin", values="found").reindex(columns=pb)
            N = x.pivot_table(index="dist", columns="pitch_bin", values="frames").reindex(columns=pb)
            W = W.where(N >= 30)
            W.columns = [f"found, pitch {c}" for c in W.columns]
            W["frames"] = N.sum(axis=1).astype("Int64")
            L += [f"## Found by obstacle distance x radar pitch ({env}, tuned CA-CFAR; blank: < 30 frames)", "",
                  md(W.reset_index().rename(columns={"dist": "true nearest (m)"}), "{:.2f}"), ""]
    Ph = C.load_table("phantom", required=False)
    if Ph is not None:
        L += ["## Alarms with nothing within 2 m: what the camera map has at that range", "",
              "Medians over sampled frames (table phantom_frames). alarm_at_floor_in_beam: share of frames whose alarm "
              "is within 0.25 m of where the floor enters the beam. Control rows: the still radar on a tripod.", "",
              md(Ph, "{:.2f}"), ""]
    A = C.load_table("ablation_summary", required=False)
    if A is not None:
        L += ["## Ablation (one change at a time from CA-CFAR defaults, each over a threshold sweep)", "",
              "pd_at_X: carried takes, arc view, best 'found' with at most X % early alarms; obj_pd_at_Y: static takes, "
              "share of placed objects (chairs, brooms) with a detection within 0.25 m of their range, with at most Y "
              "other returns per frame.", "",
              md(A[[c for c in ["axis", "variant", "pd_at_5", "pd_at_10", "pd_at_20", "auc_30", "obj_pd_at_1",
                                "obj_pd_at_2", "obj_pd_max"] if c in A]]), ""]
    Cst = C.load_table("eval_cost", required=False)
    if Cst is not None:
        Cs = Cst.groupby("family").ms_per_frame.median().reset_index()
        L += ["## Processing time per frame (this Python implementation; relative only)", "", md(Cs, "{:.3f}"), ""]
    p = C.out_dir() / "REPORT.md"
    p.write_text("\n".join(L), encoding="utf-8")
    C.log(f"  -> {C.rel(p)}")
